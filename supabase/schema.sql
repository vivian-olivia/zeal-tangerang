-- ============================================================================
-- bs_cases: RLS
-- Read+write restricted to leader/admin only: these are pastoral notes.
-- (BSDetail.jsx today has NO permission guard at all on editing them — this is
-- a real hardening over today's behavior, not a migrated regression.)
-- ============================================================================
alter table public.bs_cases enable row level security;

create policy "bs_select_leader" on public.bs_cases
  for select using (public.is_leader_or_admin());
create policy "bs_insert_leader" on public.bs_cases
  for insert with check (public.is_leader_or_admin());
create policy "bs_update_leader" on public.bs_cases
  for update using (public.is_leader_or_admin()) with check (public.is_leader_or_admin());
create policy "bs_delete_leader" on public.bs_cases
  for delete using (public.is_leader_or_admin());

-- ============================================================================
-- Invite redemption — the only two functions the public `anon` role can call
-- to touch `invites`/`members`. Both security definer, both re-validate state
-- inside the function body (never trust a prior lookup).
-- ============================================================================
create or replace function public.get_invite_by_token(p_token text)
returns table (group_id text, invited_by_name text, status text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select i.group_id, m.name, i.status
  from public.invites i
  join public.members m on m.id = i.invited_by
  where i.token = p_token
    and i.status = 'pending'
    and (i.expires_at is null or i.expires_at > now());
$$;

grant execute on function public.get_invite_by_token(text) to anon, authenticated;

-- Registration always creates a real Supabase Auth account (email+password,
-- confirmed via emailed link, or Google OAuth) before this runs — so unlike a
-- typical "redeem invite" RPC, this one requires an authenticated caller and
-- links the new member row to that session's auth.uid() directly.
create or replace function public.finalize_registration(
  p_token text,
  p_phone text,
  p_gender text,
  p_bday date,
  p_spiritual_bday date
) returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_invite public.invites%rowtype;
  v_new_id integer;
  v_name text;
  v_email text;
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'not_authenticated';
  end if;

  if exists (select 1 from public.members where auth_user_id = v_uid) then
    raise exception 'already_registered';
  end if;

  -- row-lock so two simultaneous finalize calls for the same token can't both
  -- pass the pending check before either commits
  select * into v_invite from public.invites where token = p_token for update;

  if not found or v_invite.status <> 'pending'
     or (v_invite.expires_at is not null and v_invite.expires_at <= now()) then
    raise exception 'invite_invalid_or_used';
  end if;

  select email, coalesce(raw_user_meta_data->>'name', raw_user_meta_data->>'full_name', split_part(email, '@', 1))
    into v_email, v_name
  from auth.users where id = v_uid;

  insert into public.members (name, role, group_id, phone, gender, bday, spiritual_bday, mentor_id, status, auth_user_id, email)
  values (v_name, 'member', v_invite.group_id, p_phone, p_gender, p_bday, p_spiritual_bday, v_invite.invited_by, 'Strong', v_uid, v_email)
  returning id into v_new_id;

  update public.invites set status = 'used', used_at = now() where token = p_token;

  return v_new_id;
end;
$$;

grant execute on function public.finalize_registration(text, text, text, date, date) to authenticated;
